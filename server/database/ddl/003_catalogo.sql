BEGIN;
SET LOCAL SEARCH_PATH TO SCPORTALDADOS;


/* ============================================================
   CATÁLOGO DE DADOS
   ============================================================ */
CREATE TABLE TB_CATALOGO_DADO (
    CO_SEQ_CATALOGO_DADO        BIGINT GENERATED BY DEFAULT AS IDENTITY,

    -- Identificação e classificação
    NO_CONJUNTO_DADO            VARCHAR(255) NOT NULL,
    DS_DESCRICAO               TEXT NOT NULL,
    CO_TP_DADO                 BIGINT NOT NULL,
    CO_TEMA                    BIGINT,

    -- Procedência e acesso
    NO_FONTE                   VARCHAR(200) NOT NULL,
    DS_ORIGEM                  VARCHAR(255),
    DS_IDENTIFICADOR_ORIGEM     VARCHAR(255),
    DS_URL_FONTE               TEXT,
    DS_URL_ACESSO              TEXT,
    NO_FORMATO                 VARCHAR(50),
    DS_LICENCA                 TEXT,

    -- Atualização e referência dos dados
    CO_PERIODICIDADE           BIGINT,
    DT_ULTIMA_BUSCA            TIMESTAMPTZ,
    DT_ATUALIZACAO_FONTE       DATE,
    DT_REFERENCIA_INICIO       DATE,
    DT_REFERENCIA_FIM          DATE,

    -- Cobertura e interpretação
    DS_ABRANGENCIA_TERRITORIAL  TEXT,
    DS_GRANULARIDADE           VARCHAR(150),
    DS_LIMITACOES              TEXT,

    -- Auditoria e exclusão lógica
    DT_REGISTRO                TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CO_USUARIO_REGISTRO         BIGINT NOT NULL,
    DT_ATUALIZACAO              TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CO_USUARIO_ATUALIZACAO      BIGINT NOT NULL,
    DS_OBSERVACOES              TEXT,
    ST_REGISTRO_ATIVO           INT DEFAULT 6,

    CONSTRAINT PK_TB_CATALOGO_DADO
        PRIMARY KEY (CO_SEQ_CATALOGO_DADO),
    
    CONSTRAINT FK_TB_CATALOGO_DADO_USUARIO_REGISTRO
        FOREIGN KEY (CO_USUARIO_REGISTRO)
        REFERENCES TB_USUARIO (CO_SEQ_USUARIO)
        ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT FK_TB_CATALOGO_DADO_USUARIO_ATUALIZACAO
        FOREIGN KEY (CO_USUARIO_ATUALIZACAO)
        REFERENCES TB_USUARIO (CO_SEQ_USUARIO)
        ON UPDATE RESTRICT ON DELETE RESTRICT
);

/* Índices para relacionamentos e filtros frequentes. */
CREATE INDEX IX_TB_CATALOGO_DADO_TIPO
    ON TB_CATALOGO_DADO (CO_TP_DADO);
CREATE INDEX IX_TB_CATALOGO_DADO_TEMA
    ON TB_CATALOGO_DADO (CO_TEMA);
CREATE INDEX IX_TB_CATALOGO_DADO_PERIODICIDADE
    ON TB_CATALOGO_DADO (CO_PERIODICIDADE);
CREATE INDEX IX_TB_CATALOGO_DADO_USUARIO_REGISTRO
    ON TB_CATALOGO_DADO (CO_USUARIO_REGISTRO);
CREATE INDEX IX_TB_CATALOGO_DADO_USUARIO_ATUALIZACAO
    ON TB_CATALOGO_DADO (CO_USUARIO_ATUALIZACAO);



/* ============================================================
   DOCUMENTAÇÃO DOS METADADOS
   ============================================================ */
COMMENT ON TABLE TB_CATALOGO_DADO IS 'Catálogo dos conjuntos de dados e seus metadados atuais. Não contém os dados brutos nem o histórico de coletas.';
COMMENT ON COLUMN TB_CATALOGO_DADO.NO_CONJUNTO_DADO IS 'Nome de apresentação. Não é único: edições ou recortes diferentes podem compartilhar o nome.';
COMMENT ON COLUMN TB_CATALOGO_DADO.CO_TP_DADO IS 'Natureza do dado, como tabular, geoespacial vetorial, geoespacial raster ou documental; domínio Tipo de Dado.';
COMMENT ON COLUMN TB_CATALOGO_DADO.CO_TEMA IS 'Tema principal do conjunto; domínio Tema do Dado. Múltiplos temas exigem tabela associativa.';
COMMENT ON COLUMN TB_CATALOGO_DADO.NO_FONTE IS 'Instituição ou entidade responsável pelos dados, por exemplo IBGE ou ANA.';
COMMENT ON COLUMN TB_CATALOGO_DADO.DS_ORIGEM IS 'Sistema, portal, pesquisa ou publicação de origem, por exemplo SIDRA.';
COMMENT ON COLUMN TB_CATALOGO_DADO.DS_IDENTIFICADOR_ORIGEM IS 'Código do conjunto na origem, como número da tabela, coleção ou camada.';
COMMENT ON COLUMN TB_CATALOGO_DADO.DS_URL_FONTE IS 'Página de referência ou documentação do conjunto na fonte.';
COMMENT ON COLUMN TB_CATALOGO_DADO.DS_URL_ACESSO IS 'Endereço principal para acessar o recurso: download, endpoint ou serviço. Não incluir credenciais ou URLs assinadas temporárias.';
COMMENT ON COLUMN TB_CATALOGO_DADO.NO_FORMATO IS 'Formato principal do recurso, como CSV, XLSX, GeoJSON, KML, Shapefile ou GeoTIFF. API não é formato de arquivo.';
COMMENT ON COLUMN TB_CATALOGO_DADO.DS_LICENCA IS 'Licença e condições de uso declaradas pela fonte. Nulo significa não informado.';
COMMENT ON COLUMN TB_CATALOGO_DADO.CO_PERIODICIDADE IS 'Frequência de atualização dos dados pela fonte, não o agendamento de coleta do portal; domínio Periodicidade do Dado.';
COMMENT ON COLUMN TB_CATALOGO_DADO.DT_ULTIMA_BUSCA IS 'Instante da última coleta concluída com sucesso. Nulo quando o conjunto foi apenas catalogado, ainda sem coleta.';
COMMENT ON COLUMN TB_CATALOGO_DADO.DT_ATUALIZACAO_FONTE IS 'Data de atualização da edição coletada, conforme informada pela fonte. Nulo quando desconhecida.';
COMMENT ON COLUMN TB_CATALOGO_DADO.DT_REFERENCIA_INICIO IS 'Início do período representado pelos dados; não é a data de coleta.';
COMMENT ON COLUMN TB_CATALOGO_DADO.DT_REFERENCIA_FIM IS 'Fim do período representado pelos dados; não é a data de coleta.';
COMMENT ON COLUMN TB_CATALOGO_DADO.DS_ABRANGENCIA_TERRITORIAL IS 'Área coberta pelo conjunto, como Brasil, Tocantins ou municípios do Polo.';
COMMENT ON COLUMN TB_CATALOGO_DADO.DS_GRANULARIDADE IS 'Unidade de detalhamento dos registros, como município/ano, imóvel rural ou estação/dia.';
COMMENT ON COLUMN TB_CATALOGO_DADO.DS_LIMITACOES IS 'Lacunas, restrições metodológicas, ressalvas de qualidade e cuidados de interpretação dos dados.';
COMMENT ON COLUMN TB_CATALOGO_DADO.DT_REGISTRO IS 'Instante de criação do cadastro. Preenchido por padrão pelo banco; alterações posteriores devem ser impedidas pelo backend.';
COMMENT ON COLUMN TB_CATALOGO_DADO.CO_USUARIO_REGISTRO IS 'Usuário autenticado responsável pela inclusão. Preenchido e protegido contra alterações pelo backend.';
COMMENT ON COLUMN TB_CATALOGO_DADO.DT_ATUALIZACAO IS 'Instante da última alteração do cadastro. Preenchido por padrão na inclusão e atualizado pelo backend em cada alteração.';
COMMENT ON COLUMN TB_CATALOGO_DADO.CO_USUARIO_ATUALIZACAO IS 'Usuário autenticado responsável pela última alteração. Preenchido pelo backend na inclusão, atualização e inativação.';
COMMENT ON COLUMN TB_CATALOGO_DADO.ST_REGISTRO_ATIVO IS 'TRUE: registro ativo; FALSE: inativação lógica. Não representa qualidade, publicação ou permissões de acesso.';

COMMIT;
